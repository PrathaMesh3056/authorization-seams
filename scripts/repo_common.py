#!/usr/bin/env python3
"""Shared repository inventory and hashing helpers.

The integrity model is intentionally simple: every tracked file except the
manifest itself is hashed, and any mismatch, missing file, or unexpected new
file is an error. Keep the exclusion list identical between the writer and the
verifier by importing this module from both.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST_TXT = ROOT / "artifacts" / "sha256sums.txt"
MANIFEST_JSON = ROOT / "artifacts" / "manifest.json"

EXCLUDED_DIR_NAMES = {
    ".git",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    ".venv",
    ".venv_local",
    "dist",
    "release",
    "vendor",
}
EXCLUDED_DIR_SUFFIXES = (".venv",)
EXCLUDED_RELATIVE_PREFIXES = (
    # Separate CODASPY venue cut: derivative workspace with its own build.py
    # gate, intentionally outside the canonical 319-file artifact manifest.
    "paper/venue_codaspy2027",
    "tests/authorization_pilot/vendor",
    "tests/sentinelagent_audit_20261014/upstream/.git",
    "tests/tracegrant_task_d_20261014/sources",
)
EXCLUDED_RELATIVE_FILES = {
    "artifacts/sha256sums.txt",
    "artifacts/manifest.json",
}
GENERATED_BUILD_FILES = {
    "paper/build/build_run.log",
    "paper/build/current_text.txt",
    "paper/build/final_qa_text.txt",
    "paper/build/final_refs_text.txt",
    "paper/build/final_text.txt",
    "paper/build/final_text_21.txt",
    "paper/build/fontfix_text.txt",
    "paper/build/section_sign_contexts.txt",
    "paper/latex_export/main.aux",
    "paper/latex_export/main.log",
    "paper/latex_export/main.out",
    "paper/latex_export/main.synctex.gz",
}


def rel_posix(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def is_excluded(rel: str) -> bool:
    parts = rel.split("/")
    if any(part in EXCLUDED_DIR_NAMES for part in parts):
        return True
    if any(part.endswith(EXCLUDED_DIR_SUFFIXES) for part in parts):
        return True
    if rel in EXCLUDED_RELATIVE_FILES:
        return True
    if any(rel == p or rel.startswith(p + "/") for p in EXCLUDED_RELATIVE_PREFIXES):
        return True
    if rel in GENERATED_BUILD_FILES:
        return True
    if rel.startswith("paper/build/"):
        name = parts[-1]
        # Generated by the build; the hand-written header.tex and build scripts
        # are tracked and must never be excluded by a blanket *.tex rule.
        if name.startswith("manuscript_build"):
            return True
        if name.startswith("xelatex_console"):
            return True
        if name.lower().endswith(".png"):
            return True
    return False


def tracked_files() -> list[Path]:
    files: list[Path] = []
    for path in ROOT.rglob("*"):
        if not path.is_file():
            continue
        rel = rel_posix(path)
        if is_excluded(rel):
            continue
        files.append(path)
    return sorted(files, key=rel_posix)


def sha256_file(path: Path, chunk_size: int = 1 << 20) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while True:
            chunk = handle.read(chunk_size)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest().upper()


def load_manifest() -> dict[str, str]:
    entries: dict[str, str] = {}
    if not MANIFEST_TXT.exists():
        return entries
    for line in MANIFEST_TXT.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        digest, _, rel = line.partition("  ")
        if not rel:
            digest, _, rel = line.partition(" ")
        entries[rel.strip()] = digest.strip().upper()
    return entries


def write_manifest() -> dict:
    files = tracked_files()
    lines = []
    total_bytes = 0
    for path in files:
        rel = rel_posix(path)
        lines.append(f"{sha256_file(path)}  {rel}")
        total_bytes += path.stat().st_size
    MANIFEST_TXT.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_TXT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    metadata = {
        "generated_by": "scripts/write_manifest.py",
        "algorithm": "sha256",
        "file_count": len(files),
        "total_bytes": total_bytes,
        "manifest": "artifacts/sha256sums.txt",
        "notes": (
            "Excludes .git, virtual environments, caches, dist/release staging, "
            "bootstrap vendor clones, and generated paper build output."
        ),
    }
    MANIFEST_JSON.write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return metadata
