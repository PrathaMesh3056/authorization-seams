#!/usr/bin/env python3
"""Build the arXiv-compliant named-author PDF from the frozen LaTeX export.

The canonical `paper/latex_export/main.tex` and its PDF are frozen artifacts.
This script reads that source, verifies its SHA-256, applies only the layout and
author-metadata changes required for an arXiv preprint, and writes a separate
`paper/arxiv_export/` package. It never edits the frozen source.

Layout changes:
  - 1-inch margins (arXiv minimum; the canonical draft uses 0.75 in);
  - Figure 2 is fitted to the text measure instead of a fixed 7 in width;
  - the author display name and PDF metadata use `Prathamesh N Patil`, matching
    `CITATION.cff`.

No manuscript text, claim, reference, table, or figure content is changed.
"""
from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
ROOT = PAPER.parent
SOURCE = PAPER / "latex_export" / "main.tex"
EXPECTED_SOURCE_SHA = "4C27CB582582473B961C9DD7E7574D67BD2ECB9C00CA55E6AFDDA493044D8602"
OUTDIR = PAPER / "arxiv_export"
FIGURES = PAPER / "figures"
OUT_FIGURES = OUTDIR / "figures"
OUT_TEX = OUTDIR / "main.tex"
OUT_PDF = OUTDIR / "main.pdf"

AUTHOR_OLD = "Prathamesh Patil"
AUTHOR_NEW = "Prathamesh N Patil"
MARGIN_OLD = r"\usepackage[margin=0.75in,letterpaper]{geometry}"
MARGIN_NEW = r"\usepackage[margin=1in,letterpaper]{geometry}"
FIG2_OLD = r"\includegraphics[width=7in,height=\textheight,keepaspectratio,alt={Figure"
FIG2_NEW = r"\includegraphics[width=\linewidth,height=\textheight,keepaspectratio,alt={Figure"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def replace_once(text: str, old: str, new: str, label: str) -> str:
    count = text.count(old)
    if count != 1:
        raise SystemExit(f"{label}: expected 1 occurrence, found {count}")
    return text.replace(old, new, 1)


def main() -> int:
    if not SOURCE.exists():
        raise SystemExit(f"missing frozen source: {SOURCE}")
    source_sha = sha256(SOURCE)
    if source_sha != EXPECTED_SOURCE_SHA:
        raise SystemExit(
            "frozen LaTeX source hash mismatch: "
            f"{source_sha} != {EXPECTED_SOURCE_SHA}"
        )

    text = SOURCE.read_text(encoding="utf-8")
    text = replace_once(text, MARGIN_OLD, MARGIN_NEW, "geometry")
    text = replace_once(text, FIG2_OLD, FIG2_NEW, "figure-2-width")

    # All occurrences are title-page/PDF metadata occurrences.
    author_count = text.count(AUTHOR_OLD)
    if author_count < 4:
        raise SystemExit(
            f"author metadata: expected at least 4 occurrences, found {author_count}"
        )
    text = text.replace(AUTHOR_OLD, AUTHOR_NEW)

    OUTDIR.mkdir(parents=True, exist_ok=True)
    OUT_FIGURES.mkdir(parents=True, exist_ok=True)
    for name in ("figure_1_handoff_anatomy.pdf", "figure_2_repair_loci.pdf"):
        src = FIGURES / name
        if not src.exists():
            raise SystemExit(f"missing figure: {src}")
        shutil.copy2(src, OUT_FIGURES / name)

    header = (
        "% Generated by paper/build/build_arxiv.py from the frozen\n"
        "% paper/latex_export/main.tex. Do not edit this file directly.\n"
        f"% Frozen source SHA-256: {EXPECTED_SOURCE_SHA}\n"
        "% arXiv layout: 1-inch margins, letter paper, 10 pt.\n\n"
    )
    OUT_TEX.write_text(header + text, encoding="utf-8", newline="\n")

    xelatex = shutil.which("xelatex")
    if not xelatex:
        raise SystemExit("xelatex not found on PATH")

    log_path = OUTDIR / "main.log"
    for pass_no in range(1, 4):
        result = subprocess.run(
            [xelatex, "-interaction=nonstopmode", "-halt-on-error", "main.tex"],
            cwd=OUTDIR,
            text=True,
            capture_output=True,
            check=False,
        )
        if result.returncode != 0:
            print(result.stdout[-8000:])
            print(result.stderr[-4000:], file=sys.stderr)
            raise SystemExit(f"xelatex pass {pass_no} failed with exit {result.returncode}")

    if not OUT_PDF.exists():
        raise SystemExit(f"PDF not produced: {OUT_PDF}")

    log = log_path.read_text(encoding="utf-8", errors="replace") if log_path.exists() else ""
    counts = {
        "missing_glyphs": len(re.findall(r"Missing character", log)),
        "overfull_hboxes": len(re.findall(r"Overfull \\hbox", log)),
        "underfull_hboxes": len(re.findall(r"Underfull \\hbox", log)),
        "latex_errors": len(re.findall(r"^!|LaTeX Error|Fatal error", log, re.M)),
        "label_changed": len(re.findall(r"Label\(s\) may have changed", log)),
    }

    try:
        from pypdf import PdfReader

        pages = len(PdfReader(str(OUT_PDF)).pages)
    except Exception:
        pages = -1

    # Keep the source package clean; the PDF and source are the deliverables.
    for suffix in (".aux", ".log", ".out", ".synctex.gz"):
        p = OUTDIR / f"main{suffix}"
        if p.exists():
            p.unlink()

    print(f"wrote {OUT_TEX.relative_to(ROOT)}")
    print(f"wrote {OUT_PDF.relative_to(ROOT)}")
    print(f"source_sha256={EXPECTED_SOURCE_SHA}")
    print(f"pages={pages}")
    for key, value in counts.items():
        print(f"{key}={value}")
    if counts["missing_glyphs"] or counts["latex_errors"]:
        return 1
    if counts["overfull_hboxes"]:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
